  final String id;
  final String name;
  final String role;
  final String job;
  final Color color;
  final String asset;

  static const List<Advisor> all = [
    Advisor(
      id: 'contrarian',
      name: 'Contrarian',
      role: 'What fails here?',
      job:
          'Find what is wrong with the idea. Attack weak assumptions, name the most likely failure, and say what would prove it wrong.',
      color: Color(0xFFE8483F),
      asset: 'assets/blob/contrarian.svg',
    ),
    Advisor(
      id: 'first_principles',
      name: 'First Principles',
      role: 'What are we solving?',
      job:
          'Strip the question to fundamentals. What is the real problem underneath, what job needs doing, and what facts actually matter?',
      color: Color(0xFF3B93F0),
      asset: 'assets/blob/first_principles.svg',
    ),
    Advisor(
      id: 'expansionist',
      name: 'Expansionist',
      role: 'What is the upside?',
      job:
          'Find the upside everyone is missing. How could this be bigger, bolder, or more valuable than the question assumes?',
      color: Color(0xFF3ECF8E),
      asset: 'assets/blob/expansionist.svg',
    ),
    Advisor(
      id: 'outsider',
      name: 'Outsider',
      role: 'What is confusing?',
      job:
          'Read the question with zero context, like a stranger. What is confusing, what is assumed but never said, and what would a beginner ask?',
      color: Color(0xFFF0B429),
      asset: 'assets/blob/outsider.svg',
    ),
    Advisor(
      id: 'executor',
