/// How the Bloub blob moves. One blob, one colour per advisor —
/// the motion is what changes with the action.
///
/// Animation picks (defaults where abhijeet has not chosen yet):
/// - agree → happy bounce (he rejected the wink; laughing reads angry)
/// - confused → thinking tilt (thinking wobble + a tilt)
/// - disagree → unimpressed (nearly still, slow drift)
enum BlobMood { idle, thinking, speaking, agree, disagree, confused, verdict }

/// One clarifying question the council asks the user before it runs.
/// Generated by Groq — the count is dynamic (0-5), never a fixed list.
class ClarifyingQuestion {
  ClarifyingQuestion({required this.question, this.options = const []});

  final String question;
  final List<String> options;

  factory ClarifyingQuestion.fromJson(Map<String, dynamic> json) {
    final opts = json['options'];
    return ClarifyingQuestion(
      question: (json['question'] ?? '').toString(),
      options: opts is List
          ? opts.map((e) => e.toString()).toList()
          : const [],
    );
  }
}

/// The chairman's verdict. Fixed format — never free text.
class Verdict {
  Verdict({
    required this.decision,
    required this.confidence,
    required this.why,
    required this.biggestRisk,
    required this.changesMind,
    required this.firstStep,
    required this.dissent,
  });

  /// 'Go', 'No-Go' or 'Test first'.
  final String decision;
  /// 'Low', 'Medium' or 'High'.
  final String confidence;
  final String why;
  final String biggestRisk;
  final String changesMind;
  final String firstStep;
  /// The strongest objection, kept even when the chairman disagrees.
  final String dissent;

  factory Verdict.fromJson(Map<String, dynamic> json) {
    return Verdict(
      decision: (json['decision'] ?? 'Test first').toString(),
      confidence: (json['confidence'] ?? 'Low').toString(),
      why: (json['why'] ?? '').toString(),
      biggestRisk: (json['biggest_risk'] ?? '').toString(),
      changesMind: (json['changes_mind'] ?? '').toString(),
      firstStep: (json['first_step'] ?? '').toString(),
      dissent: (json['dissent'] ?? '').toString(),
    );
  }

  Map<String, dynamic> toJson() => {
        'decision': decision,
        'confidence': confidence,
        'why': why,
        'biggest_risk': biggestRisk,
        'changes_mind': changesMind,
        'first_step': firstStep,
        'dissent': dissent,
      };

  Color get decisionColor {
    switch (decision.toLowerCase()) {
      case 'go':
        return const Color(0xFF34C759);
      case 'no-go':
        return const Color(0xFFFF3B30);
      default:
        return const Color(0xFFFF9500);
    }
  }
}

/// One advisor's first opinion (Stage 1).
class Opinion {
  Opinion({required this.advisorId, required this.text});
  final String advisorId;
  final String text;
}

/// One advisor's anonymous review of the others (Stage 2).
class Review {
  Review({
    required this.reviewerId,
    required this.ranking,
    required this.critique,
  });
  final String reviewerId;
  /// Advisor ids best-first.
  final List<String> ranking;
  final String critique;
}

/// A source from the Evidence Pack (live web facts).
class EvidenceSource {
  EvidenceSource({
    required this.title,
    required this.url,
    required this.snippet,
    this.date = '',
  });
  final String title;
  final String url;
  final String snippet;
  final String date;

  Map<String, dynamic> toJson() => {
        'title': title,
        'url': url,
        'snippet': snippet,
        'date': date,
      };

  factory EvidenceSource.fromJson(Map<String, dynamic> json) =>
      EvidenceSource(
        title: (json['title'] ?? '').toString(),
        url: (json['url'] ?? '').toString(),
        snippet: (json['snippet'] ?? '').toString(),
        date: (json['date'] ?? '').toString(),
      );
}
